#!/usr/bin/env node

import fs from "fs";
import path from "path";
import crypto from "crypto";

// -----------------------------
// INPUT: sandbox results file
// -----------------------------
const SANDBOX_REPORT = path.join(process.cwd(), "sandbox-report.json");

// -----------------------------
// LOAD SANDBOX OUTPUT
// -----------------------------
if (!fs.existsSync(SANDBOX_REPORT)) {
  console.error("[PIPELINE] missing sandbox-report.json");
  process.exit(1);
}

const sandbox = JSON.parse(fs.readFileSync(SANDBOX_REPORT, "utf-8"));

console.log("[PIPELINE] connecting sandbox → AST diff engine...");

// -----------------------------
// CI SAFETY GATE RULES
// -----------------------------
function isSafeCandidate(file) {
  return (
    file.safeToPropose === true && file.impactedCount === 0 && file.score >= 85
  );
}

// -----------------------------
// GENERATE UNIFIED PATCH
// -----------------------------
function createPatch(filePath) {
  const id = crypto
    .createHash("md5")
    .update(filePath)
    .digest("hex")
    .slice(0, 10);

  return `diff --git a/${filePath} b/${filePath}
--- a/${filePath}
+++ b/${filePath}
/* SAFE REFRACTOR SIMULATION PATCH */
/* candidate marked for removal or cleanup */
/* generated by AST pipeline v1 */

- (no-op simulation only)
+ (safe refactor placeholder)

`;
}

// -----------------------------
// PROCESS CANDIDATES
// -----------------------------
const patches = [];
const report = [];

for (const file of sandbox) {
  if (!isSafeCandidate(file)) continue;

  const patch = createPatch(file.file);

  patches.push({
    file: file.file,
    patch,
  });

  report.push({
    file: file.file,
    status: "SAFE",
    score: file.score,
  });
}

// -----------------------------
// WRITE PATCH FILES
// -----------------------------
const out = path.join(process.cwd(), "patches");
if (!fs.existsSync(out)) fs.mkdirSync(out);

for (const p of patches) {
  const fileName = path.basename(p.file).replaceAll("/", "_");
  fs.writeFileSync(path.join(out, `${fileName}.patch`), p.patch);
}

// -----------------------------
// CI GATE RESULT
// -----------------------------
const pass = patches.length > 0;

console.log("\n[PIPELINE] CI GATE RESULT:");
console.log(pass ? "✔ PASS (safe refactor batch)" : "⚠ NO SAFE CHANGES");

console.log("\n[PIPELINE] SUMMARY:");
for (const r of report) {
  console.log(`- ${r.file} | score=${r.score}`);
}

console.log("\n[PIPELINE] COMPLETE");
